USE pos_system;

-- ------------------------------------------------------------
-- 1. เพิ่มคอลัมน์ราคา 3 บิลในตาราง products
-- ------------------------------------------------------------
ALTER TABLE products
  ADD COLUMN price_tier1 DECIMAL(10,2) NULL COMMENT 'ราคาบิล 1 (ต่ำสุด)' AFTER price,
  ADD COLUMN price_tier2 DECIMAL(10,2) NULL COMMENT 'ราคาบิล 2 (กลาง)' AFTER price_tier1,
  ADD COLUMN price_tier3 DECIMAL(10,2) NULL COMMENT 'ราคาบิล 3 (สูงสุด)' AFTER price_tier2;

-- ------------------------------------------------------------
-- 2. Copy ราคาเดิมไปยัง price_tier2 (กลาง)
-- ------------------------------------------------------------
UPDATE products SET
  price_tier1 = price * 0.9,  -- บิล 1 = 90% ของราคาเดิม
  price_tier2 = price,         -- บิล 2 = ราคาเดิม
  price_tier3 = price * 1.1    -- บิล 3 = 110% ของราคาเดิม
WHERE price IS NOT NULL;

-- ------------------------------------------------------------
-- 3. ลบตาราง price_tiers (ถ้ามี)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS price_tiers;

-- ------------------------------------------------------------
-- 4. เพิ่มคอลัมน์ selected_tier ในตาราง sales_items
--    เพื่อบันทึกว่าขายด้วยบิลไหน (1/2/3)
-- ------------------------------------------------------------
ALTER TABLE sales_items
  ADD COLUMN selected_tier TINYINT DEFAULT 2 COMMENT 'บิลที่เลือก (1/2/3)' AFTER price;

-- ------------------------------------------------------------
-- หมายเหตุ:
-- - price_tier1 < price_tier2 < price_tier3
-- - ตอนเพิ่มสินค้าใหม่ ต้องกรอกราคาทั้ง 3 บิล
-- - ตอนขาย เลือกบิล → ราคาเปลี่ยนตามบิล
-- ------------------------------------------------------------
